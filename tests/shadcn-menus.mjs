import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(8000);
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
  await page.goto('http://127.0.0.1:5176');
  await page.getByRole('button', { name: 'Ceramic', exact: true }).click();
  const trigger = page.locator('#rows-per-page');
  const verifyCard = async content => {
    await content.locator(':scope > [data-oyn-layer] canvas').waitFor();
    assert.deepEqual(await content.evaluate(el => {
      const s = getComputedStyle(el);
      return [s.backgroundColor, s.boxShadow, s.overflow];
    }), ['rgba(0, 0, 0, 0)', 'none', 'visible'], 'GPU is sole card paint and shadow is not clipped');
  };
  for (const theme of ['Light', 'Dark']) {
    await page.getByRole('button', { name: theme, exact: true }).click();
    await trigger.scrollIntoViewIfNeeded();
    await page.mouse.move(700, 20);
    await page.waitForTimeout(650);
    assert.equal(await trigger.getAttribute('data-surface-elevation'), '-2.3');
    await trigger.locator('canvas').waitFor();
    await trigger.hover();
    await page.waitForTimeout(650);
    assert.equal(await trigger.getAttribute('data-surface-elevation'), '-4');
    assert.equal(await trigger.locator('canvas').count(), 1, 'one surface controls trigger paint');
    await page.mouse.move(700, 20);
    await page.waitForTimeout(650);
    assert.equal(await trigger.getAttribute('data-surface-elevation'), '-2.3');
    assert.deepEqual(await trigger.evaluate(el => [getComputedStyle(el).backgroundColor, getComputedStyle(el).boxShadow]), ['rgba(0, 0, 0, 0)', 'none']);
    await trigger.click();
    const list = page.getByRole('listbox');
    await verifyCard(list);
    const option = page.getByRole('option', { name: '30', exact: true });
    await option.hover();
    await page.waitForTimeout(650);
    assert.equal(await option.getAttribute('data-surface-elevation'), '-4');
    await option.locator('canvas').waitFor();
    assert.equal(await option.evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)');
    await page.screenshot({ path: 'test-results/menu-select-' + theme.toLowerCase() + '.png' });
    await option.click();
    await list.waitFor({ state: 'hidden' });
    assert.match(await trigger.innerText(), /30/);
    // Radix keyboard navigation remains the sole selection/focus owner.
    await trigger.focus();
    await page.keyboard.press('ArrowDown');
    await list.waitFor();
    await page.keyboard.press('Home');
    await page.waitForTimeout(650);
    const first = page.getByRole('option', { name: '10', exact: true });
    assert.equal(await first.getAttribute('data-surface-elevation'), '-4');
    await page.keyboard.press('Enter');
    await list.waitFor({ state: 'hidden' });
    assert.match(await trigger.innerText(), /10/);
    await trigger.click();
    await page.keyboard.press('Escape');
    await list.waitFor({ state: 'hidden' });
    assert.ok(await trigger.evaluate(el => el === document.activeElement));

    const columns = page.getByRole('button', { name: 'Customize Columns' });
    await columns.click();
    const menu = page.getByRole('menu');
    await verifyCard(menu);
    const checkbox = page.getByRole('menuitemcheckbox', { name: /^type$/i });
    const checked = await checkbox.getAttribute('aria-checked');
    await checkbox.hover();
    await page.waitForTimeout(650);
    assert.equal(await checkbox.getAttribute('data-surface-elevation'), '-4');
    await checkbox.locator('canvas').waitFor();
    await page.screenshot({ path: 'test-results/menu-dropdown-' + theme.toLowerCase() + '.png' });
    await checkbox.click();
    await page.waitForTimeout(250);
    if (!await menu.isVisible()) await columns.click();
    assert.notEqual(await checkbox.getAttribute('aria-checked'), checked);
    await checkbox.click();
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: /shadcn.*m@example.com/ }).click();
    const account = page.getByRole('menu');
    await verifyCard(account);
    await page.getByRole('menuitem', { name: 'Log out' }).hover();
    await page.waitForTimeout(650);
    assert.equal(await page.getByRole('menuitem', { name: 'Log out' }).getAttribute('data-surface-elevation'), '-4');
    await page.keyboard.press('Escape');
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('[data-dashboard-scroll]').evaluate(el => { el.scrollTop = 0; });
  const mobileSelect = page.getByRole('combobox', { name: 'Select a value' });
  await mobileSelect.click();
  await verifyCard(page.getByRole('listbox'));
  const mobileBounds = await page.getByRole('listbox').boundingBox();
  assert.ok(mobileBounds.x >= 0 && mobileBounds.x + mobileBounds.width <= 390);
  await page.getByRole('option', { name: 'Last 7 days', exact: true }).click();
  assert.match(await mobileSelect.innerText(), /Last 7 days/);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Original', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('[data-oyn-canvas]'));
  await trigger.click();
  assert.equal(await page.locator('[data-surface-popover]').count(), 0);
  await page.keyboard.press('Escape');
  assert.deepEqual(errors, []);
  console.log('PASS: recessed select triggers, raised unclipped popup cards, animated options/menu items, keyboard, selection, checkboxes, themes and original cleanup.');
} finally { await browser.close(); }
