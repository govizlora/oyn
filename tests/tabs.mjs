import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } });
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto('http://127.0.0.1:5176');
  const list = page.locator('[data-slot=tabs-list]').filter({ has: page.getByRole('tab', { name: 'Outline', exact: true }) });
  const tabs = list.getByRole('tab');
  await tabs.first().waitFor();
  await page.evaluate(() => { window.tabBefore = document.querySelector('[data-slot=tabs-trigger]'); });
  await page.getByRole('button', { name: 'Ceramic', exact: true }).click();
  const indicator = list.locator('[data-slot=tabs-indicator]');
  await indicator.locator('canvas').waitFor();
  await list.locator(':scope > [data-oyn-layer] > canvas').waitFor();
  assert.equal(await page.evaluate(() => window.tabBefore === document.querySelector('[data-slot=tabs-trigger]')), false);
  const box = () => indicator.evaluate(el => ({ left: parseFloat(getComputedStyle(el).left), width: parseFloat(getComputedStyle(el).width) }));
  const initial = await box();
  await tabs.nth(1).click();
  await page.waitForTimeout(60);
  const during = await box();
  await page.waitForTimeout(350);
  const end = await box();
  assert.ok(during.left > initial.left && during.left < end.left, 'selection actually slides between tabs');
  assert.ok(Math.abs(end.width - (await tabs.nth(1).boundingBox()).width) < 1, 'indicator fits unequal label widths');
  await page.keyboard.press('ArrowRight');
  await page.waitForTimeout(350);
  assert.equal(await tabs.nth(2).getAttribute('aria-selected'), 'true');
  await page.keyboard.press('Home');
  await page.waitForTimeout(100);
  assert.equal(await tabs.first().getAttribute('aria-selected'), 'true');
  await page.waitForTimeout(350);
  await list.screenshot({ path: 'test-results/tabs-light.png' });
  await page.getByRole('button', { name: 'Dark', exact: true }).click();
  await page.waitForTimeout(350);
  await list.screenshot({ path: 'test-results/tabs-dark.png' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await indicator.evaluate(el => getComputedStyle(el).transitionDuration), '0s');
  await tabs.nth(3).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(150);
  await page.setViewportSize({ width: 1600, height: 1100 });
  await page.waitForTimeout(150);
  assert.deepEqual(await indicator.boundingBox(), await tabs.nth(3).boundingBox(),
    'indicator matches the rendered tab after mobile hidden layout');
  await page.getByRole('button', { name: 'Original', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('[data-oyn-canvas]'));
  assert.equal(await tabs.first().getAttribute('aria-selected'), 'true');
  assert.equal(await indicator.count(), 0);
  assert.deepEqual(errors, []);
  console.log('Tabs: sliding geometry, keyboard, themes, reduced motion, responsive resize and mode reset passed.');
} finally { await browser.close(); }
