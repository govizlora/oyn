import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

await mkdir('test-results', { recursive: true });
const browser = await chromium.launch();
try {
  for (const [name, port] of [['mui', 5174], ['shadcn', 5175]]) {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(String(error)));
    await page.addInitScript(() => {
      window.webglRequests = 0;
      const original = HTMLCanvasElement.prototype.getContext;
      HTMLCanvasElement.prototype.getContext = function (type, ...args) {
        if (type === 'webgl' || type === 'webgl2') window.webglRequests++;
        return original.call(this, type, ...args);
      };
    });
    await page.goto('http://127.0.0.1:' + port);
    await page.getByRole('heading', { name: 'Overview', exact: true }).waitFor();
    await page.screenshot({ animations: 'disabled', path: 'test-results/' + name + '-overview.png' });
    const nav = label => page.getByRole('button', { name: label, exact: true }).first();
    await nav('Projects').click();
    await page.getByRole('textbox', { name: 'Search projects' }).fill('Website');
    assert.equal(await page.getByRole('table', { name: 'Projects', exact: true }).getByRole('row').count(), 2);
    await page.getByRole('textbox', { name: 'Search projects' }).fill('No matching project');
    await page.getByText('No projects found.', { exact: false }).waitFor();
    await page.getByRole('textbox', { name: 'Search projects' }).fill('');
    await page.getByRole('combobox', { name: 'Status', exact: true }).click();
    await page.getByRole('option', { name: 'Review', exact: true }).click();
    await page.getByRole('table', { name: 'Projects', exact: true }).waitFor();
    assert.equal(await page.getByRole('table', { name: 'Projects', exact: true }).getByRole('row').count(), 4);
    await page.getByRole('combobox', { name: 'Status', exact: true }).click();
    await page.getByRole('option', { name: 'All', exact: true }).click();
    await page.getByRole('button', { name: 'Next', exact: true }).click();
    await page.getByText('Page 2 of 2', { exact: false }).waitFor();
    await page.getByRole('button', { name: 'Previous', exact: true }).click();
    await page.getByRole('button', { name: 'Actions for API documentation', exact: true }).click();
    await page.getByRole('menuitem', { name: 'View details' }).click();
    await page.getByRole('dialog').waitFor();
    await page.getByRole('combobox', { name: 'Project status' }).click();
    await page.getByRole('option', { name: 'Completed', exact: true }).click();
    await page.getByRole('listbox').waitFor({ state: 'hidden' });
    await page.screenshot({ animations: 'disabled', path: 'test-results/' + name + '-details.png' });
    await page.keyboard.press('Escape');
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: 'New project', exact: true }).click();
    await page.getByRole('dialog').waitFor();
    await page.getByRole('textbox', { name: 'Project name', exact: true }).fill('A preview project');
    await page.getByRole('combobox', { name: 'Owner', exact: true }).click();
    await page.getByRole('option', { name: 'Sam Chen', exact: true }).click();
    await page.getByRole('listbox').waitFor({ state: 'hidden' });
    await page.screenshot({ animations: 'disabled', path: 'test-results/' + name + '-dialog.png' });
    await page.getByRole('button', { name: 'Create project', exact: true }).click();
    await page.getByRole('button', { name: 'A preview project', exact: true }).waitFor();
    await page.getByRole('checkbox', { name: 'Select A preview project', exact: true }).check();
    await page.getByRole('button', { name: 'Archive selected', exact: true }).click();
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    assert.equal(await page.getByRole('button', { name: 'A preview project', exact: true }).count(), 1);
    await page.getByRole('button', { name: 'Archive selected', exact: true }).click();
    await page.getByRole('button', { name: 'Archive', exact: true }).click();
    await page.getByRole('button', { name: 'A preview project', exact: true }).waitFor({ state: 'hidden' });
    await page.screenshot({ animations: 'disabled', path: 'test-results/' + name + '-projects.png' });
    await nav('Team').click();
    await page.getByRole('button', { name: 'Invite member', exact: true }).click();
    await page.getByRole('textbox', { name: 'Email address', exact: true }).fill('demo@example.com');
    await page.getByRole('button', { name: 'Add invitation', exact: true }).click();
    await page.getByRole('cell', { name: 'demo@example.com', exact: true }).waitFor();
    await nav('Settings').click();
    await page.getByRole('tab', { name: 'Notifications', exact: true }).click();
    await page.getByRole('switch', { name: 'Product updates', exact: true }).check();
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    await page.getByText('Settings saved for this preview', { exact: true }).waitFor();
    assert.equal(await page.locator('[data-oyn-canvas], canvas').count(), 0);
    assert.equal(await page.evaluate(() => window.webglRequests), 0);

    await page.setViewportSize({ width: 390, height: 844 });
    await page.reload();
    await page.getByRole('heading', { name: 'Overview', exact: true }).waitFor();
    await page.getByRole('button', { name: name === 'mui' ? 'Open navigation' : 'Toggle Sidebar', exact: true }).click();
    await nav('Projects').click();
    await page.getByRole('heading', { name: 'Projects', exact: true }).waitFor();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), name + ': mobile page must not overflow');
    await page.screenshot({ animations: 'disabled', path: 'test-results/' + name + '-mobile.png' });
    assert.deepEqual(errors, []);
    console.log(name + ': navigation, search, select, pagination, row menu, details, dialog, selection, invite, settings, mobile; zero Surface/WebGL.');
    await page.close();
  }
} finally { await browser.close(); }
