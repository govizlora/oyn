// Compile assembled production WGSL, not separately maintained GLSL.
import { createServer } from "vite";
import { writeFile, readFile } from "node:fs/promises";
import { parseWgsl, validate, writeGlsl } from "naga-wasm";
const dir = new URL("../../packages/ceramic/src/", import.meta.url);
const vite = await createServer({
  root: new URL("../../", import.meta.url).pathname,
  server: { middlewareMode: true, hmr: false },
});
try {
  for (const [file, entries] of Object.entries({
    ceramic: [
      ["shaders", "ceramicWGSL"],
      ["inset", "insetWGSL"],
    ],
    card: [["card", "cardWGSL"]],
    "flip-disc": [["flip-disc", "flipDiscWGSL"]],
  })) {
    let code = "// Generated by tools/webgl/generate.mjs. Do not edit.\n";
    const programs = [];
    for (const [path, key] of entries) {
      code += `import {${key}} from "../${path}.js";\n`;
      const wgsl = (
        await vite.ssrLoadModule("/packages/ceramic/src/" + path + ".ts")
      )[key];
      const module = parseWgsl(wgsl),
        info = validate(module),
        blocks = {};
      function compile(stage, entryPoint) {
        const result = writeGlsl(module, info, {
          version: "300 es",
          stage,
          entryPoint,
          reflect: true,
          flags: { adjustCoordinateSpace: false },
        });
        for (const [name, { binding }] of Object.entries(
          result.reflection.uniforms,
        ))
          blocks[name] = binding;
        return result.code;
      }
      const vertex = compile("vertex", "vertex"),
        fragments = {};
      for (const [, name] of wgsl.matchAll(/@fragment\s+fn\s+(\w+)/g))
        fragments[name] = compile("fragment", name);
      programs.push(
        `[${key},${JSON.stringify({ vertex, fragments, blocks })}]`,
      );
      info.free();
      module.free();
    }
    code +=
      "export default new Map<string,{vertex:string, fragments:Record<string,string>, blocks:Record<string,number>}>([" +
      programs.join(",") +
      "]);\n";
    const dest = new URL("generated/" + file + ".ts", dir);
    if (process.argv.includes("--check")) {
      if ((await readFile(dest, "utf8")) !== code)
        throw Error("Stale generated shader: " + file);
    } else await writeFile(dest, code);
  }
} finally {
  await vite.close();
}
